"""
Quick Article Generator - Generates an article for "Python Machine Learning"
"""

import requests
import json
import os
from datetime import datetime

BACKEND_URL = "http://localhost:8000"
OUTPUT_FOLDER = "output"

def ensure_output_folder():
    """Create output folder if it doesn't exist."""
    if not os.path.exists(OUTPUT_FOLDER):
        os.makedirs(OUTPUT_FOLDER)

def generate_demo_article():
    """Generate a demo article about Python Machine Learning."""
    
    print("🤖 Quick AI Article Generator Demo")
    print("=" * 40)
    
    # Check if backend is running
    try:
        response = requests.get(f"{BACKEND_URL}/health")
        if response.status_code != 200:
            print("❌ Backend server is not responding properly")
            print("   Please start the server with: python minimal_server.py")
            return
        print("✅ Backend server is running")
    except:
        print("❌ Cannot connect to backend server")
        print(f"   Make sure server is running on {BACKEND_URL}")
        print("   Start with: python minimal_server.py")
        return
    
    # Generate article for demo topic
    topic = "Python Machine Learning for Beginners"
    depth = "beginner"
    
    print(f"\n🚀 Generating demo article...")
    print(f"   Topic: {topic}")
    print(f"   Audience: {depth}")
    
    try:
        # Create job
        job_data = {
            "topic": topic,
            "desired_depth": depth,
            "max_length": 5000,
            "include_visuals": True
        }
        
        response = requests.post(f"{BACKEND_URL}/v1/jobs", json=job_data)
        
        if response.status_code != 200:
            print(f"❌ Failed to create job: {response.status_code}")
            print(f"   Response: {response.text}")
            return
        
        job_result = response.json()
        job_id = job_result["job_id"]
        print(f"   ✅ Job created: {job_id}")
        
        # Get result
        result_response = requests.get(f"{BACKEND_URL}/v1/jobs/{job_id}")
        
        if result_response.status_code != 200:
            print(f"❌ Failed to get result: {result_response.status_code}")
            return
        
        job_data = result_response.json()
        
        if "result" not in job_data or "article" not in job_data["result"]:
            print("❌ No article found in response")
            print("Raw response:")
            print(json.dumps(job_data, indent=2))
            return
        
        article = job_data["result"]["article"]
        
        # Show results
        print(f"\n📊 Article Generated Successfully!")
        print(f"   📖 Title: {article.get('title', 'No title')}")
        print(f"   📝 Word Count: {article.get('word_count', 0)}")
        print(f"   🤖 AI Powered: {article.get('ai_powered', False)}")
        print(f"   🔧 Method: {article.get('generation_method', 'unknown')}")
        
        # Save to file
        ensure_output_folder()
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        filename = f"{timestamp}_demo_python_ml.md"
        filepath = os.path.join(OUTPUT_FOLDER, filename)
        
        # Create markdown content
        markdown_content = f"""# {article.get('title', topic)}

**Generated:** {datetime.now().strftime("%Y-%m-%d %H:%M:%S")}  
**Topic:** {topic}  
**Audience:** {depth}  
**Word Count:** {article.get('word_count', 0)}  
**AI Powered:** {article.get('ai_powered', False)}  
**Method:** {article.get('generation_method', 'unknown')}  

---

{article.get('content', 'No content available')}

---

*Generated by AI Article Generator Demo*
"""
        
        with open(filepath, 'w', encoding='utf-8') as f:
            f.write(markdown_content)
        
        print(f"\n✅ Article saved successfully!")
        print(f"   📁 File: {filepath}")
        print(f"   📄 Size: {os.path.getsize(filepath)} bytes")
        
        # Show preview
        content_preview = article.get('content', '')[:500]
        print(f"\n📃 Content Preview:")
        print("-" * 50)
        print(content_preview)
        if len(article.get('content', '')) > 500:
            print("...")
        print("-" * 50)
        
        print(f"\n🎉 Demo complete! Open '{filepath}' to see the full article.")
        
    except Exception as e:
        print(f"❌ Error: {e}")
        import traceback
        traceback.print_exc()

if __name__ == "__main__":
    generate_demo_article()
